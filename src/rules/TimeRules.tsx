/** どのゲームにも共通する、持ち時間（対局時計）の説明 */

const COMMON_USE: Record<string, string> = {
  chess: '公式戦ではフィッシャー方式（例：90分＋1手30秒）が主流です。米国では遅延方式も使われます。',
  shogi: 'プロ・アマとも「持ち時間を使い切ったら1手30秒（または60秒）の秒読み」が主流です。ネット対局では切れ負けやフィッシャー方式も使われます。',
  go: '日本の棋戦では「持ち時間＋秒読み（30秒を数回）」、欧米ではカナダ式、ネット対局ではフィッシャー方式もよく使われます。',
  othello: '日本オセロ連盟の公式戦は、1人30分程度の切れ負けが一般的です。',
  gomoku: '大会によって切れ負け・フィッシャー方式・秒読みが使い分けられています。',
};

export function TimeRules({ gameId }: { gameId: string }) {
  return (
    <>
      <h2>持ち時間（対局時計）</h2>
      <p>
        大会では、考える時間に制限を設けるため対局時計を使います。自分の手番の間だけ自分の時計が減り、
        <strong>時間を使い切ると負け（時間切れ負け）</strong>になります。方式は大会によって異なります。
      </p>
      <dl>
        <dt>切れ負け</dt>
        <dd>決められた持ち時間を使い切ったら負けです。</dd>
        <dt>秒読み</dt>
        <dd>
          持ち時間を使い切った後は、1手を決められた秒数（例：30秒）以内に指せば負けになりません。囲碁では「30秒×3回」のように回数があり、
          秒数を超えるたびに1回分を消費し、なくなったら負けです（1手を秒数以内に指せば回数は減りません）。
        </dd>
        <dt>フィッシャー方式</dt>
        <dd>1手指すごとに決められた秒数（例：5秒）が持ち時間に加算されます。</dd>
        <dt>カナダ式</dt>
        <dd>持ち時間を使い切った後は、決められた時間（例：5分）の中で決められた手数（例：25手）を指します。指し終えると時間が元に戻ります。</dd>
        <dt>遅延（ディレイ）</dt>
        <dd>毎手、決められた秒数（例：5秒）までは持ち時間が減りません。それを超えた分だけ減ります。</dd>
      </dl>
      <p>{COMMON_USE[gameId]}</p>
      <h3>このアプリでの扱い</h3>
      <ul>
        <li>「新しい対局」で方式と時間を選べます。よく使われる設定はプリセットから選べます。</li>
        <li>アプリを閉じたり画面が消えたりしている間は、時計が止まります。</li>
        <li>CPU は残り時間に合わせて考える時間を短くします。</li>
        <li>「待った」をすると、時計もその局面の時点に戻ります。</li>
      </ul>
    </>
  );
}
