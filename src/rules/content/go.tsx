/** 置石の配置図（19路） */
function handicapRows(stones: number): string[] {
  const pts = new Set(handicapPoints(19, stones));
  const rows: string[] = [];
  for (let r = 0; r < 19; r++) {
    let row = '';
    for (let c = 0; c < 19; c++) row += pts.has(r * 19 + c) ? 'X' : '.';
    rows.push(row);
  }
  return rows;
}
